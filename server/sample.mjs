export function sampleDay(city, index) {
  const places = catalog[city] ?? catalog['เชียงใหม่'];
  const start = (index * 3) % places.length;
  return {
    title: ['เดินรอบเมืองเก่า', 'ออกไปสัมผัสธรรมชาติ', 'เก็บจุดโปรดก่อนกลับ'][index % 3],
    stops: places.slice(start, start + 3).map(([name, kind, lat, lon, cost], i) => ({
      id: 'd' + (index + 1) + '_' + (i + 1), name, kind, ll: [lat, lon], cost,
      start: ['10:00', '12:15', '15:00'][i], end: ['11:10', '13:20', '16:10'][i],
      mode: i === 1 ? 'red' : 'walk', diet: [],
    })),
  };
}
